# 隱藏名店額外鉤子
HIDDEN_GEM_HOOK = '⟡ 公會密報：此據點鮮為人知卻評價極高，疑為深藏不露的隱藏名店，賞金加倍。'


def _pick(pool, seed_str):
    """依種子字串穩定地從 pool 選一個（同店每天看到同一個，不亂跳）"""
    idx = int(hashlib.md5(seed_str.encode()).hexdigest(), 16) % len(pool)
    return pool[idx]


def make_flavor(shop, grade, is_hidden_gem):
    """
    產生一張懸賞令的風味文案。

    shop: dict，需有 'id'、'cuisine'（可 None）、'district'（可 None）
    grade: 'S'|'A'|'B'|'C'
    is_hidden_gem: bool

    回傳 dict：
      quest_title: 委託標題（疊在店名上方），如「討伐：北安路的綠衣女妖」
      quest_desc:  風味敘述（分級語氣 + 料理特徵 + 隱藏鉤子）
      monster_tag: 短怪物標籤，可放在分類標籤位置，如「咖啡因魔物」
    """
    cuisine = (shop.get('cuisine') or '').strip()
    table = CUISINE_FLAVOR.get(cuisine, _DEFAULT)

    sid = str(shop.get('id', ''))
    monster = _pick(table['monster'], sid + 'm')
    verb = _pick(table['verb'], sid + 'v')
    trait = _pick(table['trait'], sid + 't')

    # 地點詞：取地址裡的路名更有味，退而求其次用 district
    locale = shop.get('district') or '未知之地'

    quest_title = f'{verb}：{locale}的{monster}'

    desc_parts = [GRADE_TONE.get(grade, ''), trait]
    if is_hidden_gem:
        desc_parts.append(HIDDEN_GEM_HOOK)
    quest_desc = ' '.join(p for p in desc_parts if p)

    return {
        'quest_title': quest_title,
        'quest_desc': quest_desc,
        'monster_tag': monster,
    }
